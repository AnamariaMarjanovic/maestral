import { Oklch, contrast, formatOklch, oklchToHex, parseHex, rgbToOklch, toGamut } from './color';

export type ThemeShape = 'sail' | 'rounded' | 'square' | 'pill';
export type ThemeDensity = 'compact' | 'comfortable' | 'spacious';

export interface ThemeInput {
  readonly primary: string;
  readonly shape: ThemeShape;
  readonly density: ThemeDensity;
}

export interface ContrastCheck {
  readonly mode: 'Light' | 'Dark';
  readonly label: string;
  readonly ratio: number;
  readonly minimum: number;
  readonly pass: boolean;
}

export interface Theme {
  /** Custom properties to apply, by name. */
  readonly tokens: Readonly<Record<string, string>>;
  /** The same tokens as a stylesheet to paste into an app. */
  readonly css: string;
  readonly checks: readonly ContrastCheck[];
  /** Set when the light-mode primary had to be darkened to meet AA. */
  readonly adjustedFrom: string | null;
  readonly lightPrimaryHex: string;
}

// The parts of Maestral's own palette the primary color is checked against
const WHITE: Oklch = { l: 1, c: 0, h: 0 };
const DARK_BG: Oklch = { l: 0.16, c: 0.025, h: 265 };

const SHAPES: Record<ThemeShape, { sail: string; tack: string }> = {
  sail: { sail: '0.875rem', tack: '0.1875rem' },
  rounded: { sail: '0.5rem', tack: '0.5rem' },
  square: { sail: '0.125rem', tack: '0.125rem' },
  pill: { sail: '9999px', tack: '9999px' },
};

const CONTROL_HEIGHTS: Record<ThemeDensity, string> = {
  compact: '2rem',
  comfortable: '2.5rem',
  spacious: '3rem',
};

const TEXT = 4.5;
const FOCUS = 3;

interface Palette {
  readonly primary: Oklch;
  readonly hover: Oklch;
  readonly subtle: Oklch;
  readonly on: Oklch;
}

const at = (base: Oklch, l: number, c = base.c): Oklch => toGamut({ l, c, h: base.h });

/**
 * Light mode: the primary carries white text and is used as text on white,
 * so it must be dark enough for 4.5:1 against both. Start at the chosen
 * lightness and darken only as far as needed.
 */
function lightPalette(base: Oklch): Palette {
  const subtle = at(base, 0.97, Math.min(base.c, 0.02));
  let l = Math.min(base.l, 0.95);
  let primary = at(base, l);
  while ((contrast(WHITE, primary) < TEXT || contrast(primary, subtle) < TEXT) && l > 0.1) {
    l -= 0.005;
    primary = at(base, l);
  }
  return {
    primary,
    hover: at(base, Math.max(0.1, l - 0.07), Math.min(base.c, base.c * 0.88)),
    subtle,
    on: WHITE,
  };
}

/**
 * Dark mode: the primary is used as text on the dark page and carries dark
 * text, so it must be light enough for 4.5:1 against both.
 */
function darkPalette(base: Oklch): Palette {
  const subtle = at(base, 0.28, Math.min(base.c, 0.06));
  // Same starting point as Maestral's own dark palette: light and soft
  let l = 0.76;
  let primary = at(base, l, Math.min(base.c, 0.11));
  while (
    (contrast(primary, DARK_BG) < TEXT || contrast(primary, subtle) < TEXT) &&
    l < 0.98
  ) {
    l += 0.005;
    primary = at(base, l, Math.min(base.c, 0.11));
  }
  return {
    primary,
    hover: at(base, Math.min(0.96, l + 0.1), Math.min(base.c, 0.07)),
    subtle,
    on: DARK_BG,
  };
}

function checks(mode: ContrastCheck['mode'], palette: Palette, page: Oklch): ContrastCheck[] {
  const check = (label: string, a: Oklch, b: Oklch, minimum: number): ContrastCheck => {
    const ratio = contrast(a, b);
    return { mode, label, ratio, minimum, pass: ratio >= minimum - 1e-6 };
  };
  return [
    check('Button text on primary', palette.on, palette.primary, TEXT),
    check('Button text on hover', palette.on, palette.hover, TEXT),
    check('Links and ghost buttons on the page', palette.primary, page, TEXT),
    check('Ghost button on its hover background', palette.primary, palette.subtle, TEXT),
    check('Focus ring on the page', palette.primary, page, FOCUS),
  ];
}

export function buildTheme(input: ThemeInput): Theme | null {
  const rgb = parseHex(input.primary);
  if (!rgb) {
    return null;
  }
  const base = rgbToOklch(rgb);
  const light = lightPalette(base);
  const dark = darkPalette(base);

  const pair = (a: Oklch, b: Oklch) => `light-dark(${formatOklch(a)}, ${formatOklch(b)})`;
  const shape = SHAPES[input.shape];
  const tokens: Record<string, string> = {
    '--ms-color-primary': pair(light.primary, dark.primary),
    '--ms-color-primary-hover': pair(light.hover, dark.hover),
    '--ms-color-primary-subtle': pair(light.subtle, dark.subtle),
    '--ms-color-on-primary': pair(light.on, dark.on),
    '--ms-radius-sail': shape.sail,
    '--ms-radius-tack': shape.tack,
    '--ms-control-height': CONTROL_HEIGHTS[input.density],
  };

  const css = [
    '/* Generated by the Maestral theme builder. Add after maestral.css. */',
    ':root {',
    ...Object.entries(tokens).map(([name, value]) => `  ${name}: ${value};`),
    '}',
  ].join('\n');

  const requestedHex = oklchToHex(toGamut(base)).toLowerCase();
  const lightPrimaryHex = oklchToHex(light.primary).toLowerCase();

  return {
    tokens,
    css,
    checks: [...checks('Light', light, WHITE), ...checks('Dark', dark, DARK_BG)],
    adjustedFrom: Math.abs(light.primary.l - base.l) > 0.004 ? requestedHex : null,
    lightPrimaryHex,
  };
}
